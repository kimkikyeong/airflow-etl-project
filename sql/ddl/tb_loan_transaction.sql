CREATE TABLE SYSTEM.TB_LOAN_TRANSACTION (
	TX_SEQ			NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
	TX_DATE			VARCHAR2(8)		NOT NULL,	-- 거래일자 (YYYYMMDD)
	CUST_ID			VARCHAR2(10)	NOT NULL,	-- 고객번호
	PRODUCT_CODE	VARCHAR2(10)	NOT NULL,	-- 대출 상품 코드
	TX_TYPE			VARCHAR2(10)	NOT NULL,	-- 거래유형 (신규/상환/이자)
	TX_AMOUNT		NUMBER(15,2)	NOT NULL,	-- 거래금액
	CREATE_TIME		TIMESTAMP DEFAULT SYSTIMESTAMP 
);